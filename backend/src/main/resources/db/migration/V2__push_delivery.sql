CREATE TABLE push_delivery (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id bigint NOT NULL,
    notification_id bigint,
    token character varying(255) NOT NULL,
    title character varying(200) NOT NULL,
    body character varying(1000) NOT NULL,
    notification_type character varying(255) NOT NULL,
    status character varying(20) NOT NULL,
    ticket_id character varying(255) UNIQUE,
    attempts integer NOT NULL,
    last_error character varying(255),
    ticketed_at timestamp with time zone,
    next_check_at timestamp with time zone,
    created_at timestamp with time zone NOT NULL
);

CREATE INDEX idx_push_delivery_due ON push_delivery USING btree (next_check_at, id) WHERE status = 'CHECKING';
CREATE INDEX idx_push_delivery_user_id ON push_delivery USING btree (user_id);
CREATE INDEX idx_push_delivery_created_at ON push_delivery USING btree (created_at);
